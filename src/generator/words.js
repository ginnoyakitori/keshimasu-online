function getPlayableWords(options = {}) {
  const minLen = options.minLen ?? 2;

  // 仕様上、最大5文字
  const maxLen = Math.min(
    options.maxLen ?? MAX_WORD_LENGTH,
    MAX_WORD_LENGTH
  );

  return WORDS.filter((word) => {
    const len = [...word].length;
    return len >= minLen && len <= maxLen;
  });
}

